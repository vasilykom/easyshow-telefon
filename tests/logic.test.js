import { test } from 'node:test';
import assert from 'node:assert/strict';
import {
  годныйНомерПлана, ближайшееВоскресенье, годнаяДата, новыйНомерПлана,
  текстПлана, новыйПлан, путьПлана, ближайшиеПланы, вBase64,
} from '../logic.js';

test('номер плана — по правилу программы (priyom.rs, годный_номер_плана)', () => {
  assert.ok(годныйНомерПлана('tel-2026-10-18-ab12cd'));
  assert.ok(!годныйНомерПлана(''));
  assert.ok(!годныйНомерПлана('план'));
  assert.ok(!годныйНомерПлана('a/b'));
  assert.ok(!годныйНомерПлана('x'.repeat(81)));
  assert.ok(годныйНомерПлана('x'.repeat(80)));
});

test('ближайшее воскресенье: из четверга — через три дня, из воскресенья — сегодня', () => {
  assert.equal(ближайшееВоскресенье(new Date(2026, 9, 15)), '2026-10-18');
  assert.equal(ближайшееВоскресенье(new Date(2026, 9, 18)), '2026-10-18');
  assert.equal(ближайшееВоскресенье(new Date(2026, 9, 19)), '2026-10-25');
  assert.equal(ближайшееВоскресенье(new Date(2026, 11, 28)), '2027-01-03');
});

test('дата: только настоящая ГГГГ-ММ-ДД', () => {
  assert.ok(годнаяДата('2026-10-18'));
  assert.ok(!годнаяДата('2026-02-30'));
  assert.ok(!годнаяДата('18.10.2026'));
});

test('новый номер: tel-<дата>-<6 знаков> и годится программе', () => {
  const н = новыйНомерПлана('2026-10-18', () => 0.5);
  assert.match(н, /^tel-2026-10-18-[a-z0-9]{6}$/);
  assert.ok(годныйНомерПлана(н));
});

test('текст плана — как serde_json::to_string_pretty + перевод строки', () => {
  const план = новыйПлан({
    дата: '2026-10-18', название: 'Воскресенье', номер: 'tel-2026-10-18-aaaaaa', сейчасМс: 1760000000000,
    песни: [{ id: 's1', title: 'Песня один' }],
  });
  // Образец набран руками в виде serde: два пробела, порядок ключей, "[]" у пустого.
  assert.equal(текстПлана(план), `{
  "id": "tel-2026-10-18-aaaaaa",
  "name": "Воскресенье",
  "date": "2026-10-18",
  "items": [
    {
      "id": "tel-2026-10-18-aaaaaa-1",
      "type": "song",
      "songId": "s1",
      "title": "Песня один"
    }
  ],
  "updatedAt": 1760000000000
}
`);
  const пустой = новыйПлан({ дата: '2026-10-18', название: '', номер: 'tel-x', сейчасМс: 1, песни: [] });
  assert.match(текстПлана(пустой), /"items": \[\],/);
  assert.equal(пустой.name, 'Служение');
});

test('новый план не примет плохую дату или номер', () => {
  assert.throws(() => новыйПлан({ дата: '2026-13-01', номер: 'tel-x', сейчасМс: 1 }));
  assert.throws(() => новыйПлан({ дата: '2026-10-18', номер: 'плохой', сейчасМс: 1 }));
});

test('путь: дата свободна — <дата>.json, занята — <дата>_<id>.json', () => {
  const план = { id: 'tel-a', date: '2026-10-18' };
  assert.equal(путьПлана(план, new Set()), 'plany/2026-10-18.json');
  assert.equal(путьПлана(план, new Set(['2026-10-18.json'])), 'plany/2026-10-18_tel-a.json');
});

test('ближайшие планы: прошлые и без даты скрыты, по дате', () => {
  const планы = [
    { id: '1', name: 'Б', date: '2026-10-25' },
    { id: '2', name: 'А', date: '2026-10-18' },
    { id: '3', name: 'Старый', date: '2026-10-11' },
    { id: '4', name: 'Без даты', date: '' },
  ];
  assert.deepEqual(ближайшиеПланы(планы, '2026-10-15').map((п) => п.id), ['2', '1']);
});

test('base64 держит кириллицу', () => {
  const т = 'Слава 🎵';
  assert.equal(Buffer.from(вBase64(т), 'base64').toString('utf8'), т);
});
